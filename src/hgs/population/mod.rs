//! Population management for HGS — subpopulations, fitness, tournaments, penalties, and MDM pattern mining.
//!
//! The population maintains two sorted subpopulations (feasible and infeasible), each ordered by
//! increasing penalized cost. Survivor selection removes the worst-biased-fitness individual when
//! the pool exceeds `minimum_population_size + generation_size`.

use std::collections::VecDeque;

use crate::hgs::{local_search::HGSLocalSearch, Individual, Params, SortableF64, Split};

type SubPop<'p> = Vec<Box<Individual<'p>>>;

use crate::hgs::params::MY_EPSILON;

/// Population of a Genetic Algorithm with functionality for survivor selection, diversity tracking,
/// penalty management, and MDM pattern mining.
pub struct Population<'p> {
    params: &'p Params,
    pub(crate) collected_routes: Option<std::collections::BTreeSet<Vec<usize>>>,

    /// Feasible subpopulation (pool), ordered by increasing penalized cost.
    pub feasible: SubPop<'p>,
    /// Infeasible subpopulation (pool), ordered by increasing penalized cost.
    pub infeasible: SubPop<'p>,

    /// Load feasibility of the last 100 individuals generated by local search.
    last_feas_load: VecDeque<bool>,
    /// Time-warp feasibility of the last 100 individuals generated by local search.
    last_feas_tw: VecDeque<bool>,

    /// Search progress — (elapsed_seconds, best_penalized_cost) at each improvement.
    pub search_progress: Vec<(f64, f64)>,

    /// Best solution found during the current restart.
    pub best_restart: Box<Individual<'p>>,
    /// Best solution found overall.
    pub best_overall: Box<Individual<'p>>,

    /// MDM elite set.
    pub mdm_elite: Vec<Box<Individual<'p>>>,
    pub mdm_elite_updated: bool,
    pub mdm_elite_max_non_updating_restarts: usize,
    /// Restarts since the elite set last changed.
    pub mdm_elite_non_updating_restarts: usize,
    /// Mined patterns: each is a set of route fragments.
    pub mdm_patterns: Vec<Vec<Vec<usize>>>,
    pub mdm_next_pattern: usize,
    /// Total number of generations executed.
    pub nb_generations: u32,
    /// Target pool size (mu); starts at the configured value and may grow.
    pub minimum_population_size: i32,
}

